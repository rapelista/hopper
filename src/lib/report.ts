import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { HopperStore } from "./store"
import type { Finding } from "./store"
import type { Severity } from "./findings"

const SEVERITY_ORDER: Record<Severity, number> = { critical: 0, high: 1, medium: 2, low: 3, info: 4 }

export function renderReportMarkdown(store: HopperStore, opId: string): string {
  const op = store.listOperations().find((o) => o.id === opId) ?? null
  const findings = store.listFindings(opId)
  const lines: string[] = []

  lines.push(`# Security Report — ${op?.name ?? "operation"}`)
  lines.push("")
  lines.push(`- Target: ${op?.target ?? "unknown"}`)
  lines.push(`- Operation status: ${op?.status ?? "unknown"}`)
  lines.push(`- Generated: ${new Date().toISOString()}`)
  lines.push("")

  const counts = new Map<string, number>()
  for (const f of findings) counts.set(f.status, (counts.get(f.status) ?? 0) + 1)
  lines.push("## Summary")
  lines.push("")
  if (findings.length === 0) {
    lines.push("No findings recorded.")
  } else {
    lines.push(`Total findings: ${findings.length} (${[...counts.entries()].map(([s, n]) => `${n} ${s}`).join(", ")})`)
  }
  lines.push("")

  if (findings.length > 0) {
    lines.push("## Findings")
    lines.push("")
    lines.push("| Severity | Status | Title | Target |")
    lines.push("|---|---|---|---|")
    for (const f of [...findings].sort((a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity])) {
      lines.push(`| ${f.severity} | ${f.status} | ${f.title} | ${f.target} |`)
    }
    lines.push("")

    const reportable = findings.filter((f) => f.status === "reportable")
    if (reportable.length > 0) {
      lines.push("## Reportable findings — detail")
      lines.push("")
      for (const f of reportable) {
        lines.push(`### [${f.severity}] ${f.title}`)
        lines.push("")
        lines.push(`- Status: ${f.status} | Target: ${f.target}`)
        if (f.notes) lines.push(`- Notes: ${f.notes}`)
        const evidence = store.listEvidence(opId, f.id)
        if (evidence.length > 0) {
          lines.push("- Evidence:")
          for (const e of evidence) {
            lines.push(`  - ${e.kind} ${e.id} (${e.size}B, sha256 ${e.sha256.slice(0, 16)}…)`)
          }
        }
        lines.push("")
      }
    }
  }

  lines.push("---")
  lines.push("Generated by Hopper")
  return lines.join("\n")
}

export function writeReport(configDir: string, opId?: string): string {
  const store = HopperStore.open(configDir)
  try {
    const id = opId ?? store.getActiveOperation()?.id
    if (!id) throw new Error("no operation to report on")
    const md = renderReportMarkdown(store, id)
    const op = store.listOperations().find((o) => o.id === id)
    const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, "")
    const reportsDir = join(configDir, "..", "reports")
    mkdirSync(reportsDir, { recursive: true })
    const path = join(reportsDir, `${id.slice(0, 8)}-${op?.name ?? "operation"}-${stamp}.md`)
    writeFileSync(path, md)
    return path
  } finally {
    store.close()
  }
}
