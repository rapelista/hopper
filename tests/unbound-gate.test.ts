import { describe, expect, test } from "bun:test"
import { createUnboundGate, type GuardAsk } from "../src/lib/unbound-gate"

const ask = (over: Partial<GuardAsk> = {}): GuardAsk => ({
  askId: "ask-1",
  sessionID: "ses-1",
  messageID: "msg-1",
  tool: "bash",
  targets: ["evil.test"],
  reason: "outside scope",
  ...over,
})

describe("createUnboundGate.decide/answer", () => {
  test("emits the ask and resolves the operator's choice", async () => {
    const emitted: GuardAsk[] = []
    const gate = createUnboundGate({ emit: (a) => emitted.push(a) })
    const pending = gate.decide(ask())
    expect(emitted).toHaveLength(1)
    expect(emitted[0]!.targets).toEqual(["evil.test"])
    expect(gate.answer(emitted[0]!.askId, "deny")).toBe(true)
    expect(await pending).toEqual({ choice: "deny" })
  })

  test("bind passes operationId through", async () => {
    const gate = createUnboundGate({ emit: () => {} })
    const pending = gate.decide(ask())
    expect(gate.answer("ask-1", "bind", "op-42")).toBe(true)
    expect(await pending).toEqual({ choice: "bind", operationId: "op-42" })
  })

  test("free and allow-once resolve without operationId", async () => {
    const gate = createUnboundGate({ emit: () => {} })
    const a = gate.decide(ask({ askId: "a" }))
    const b = gate.decide(ask({ askId: "b" }))
    expect(gate.answer("a", "free")).toBe(true)
    expect(gate.answer("b", "allow-once")).toBe(true)
    expect(await a).toEqual({ choice: "free" })
    expect(await b).toEqual({ choice: "allow-once" })
  })

  test("answer returns false for unknown askId", () => {
    const gate = createUnboundGate({ emit: () => {} })
    expect(gate.answer("nope", "deny")).toBe(false)
  })

  test("answer returns false after resolution", async () => {
    const gate = createUnboundGate({ emit: () => {} })
    const pending = gate.decide(ask())
    expect(gate.answer("ask-1", "deny")).toBe(true)
    expect(gate.answer("ask-1", "bind")).toBe(false)
    expect(await pending).toEqual({ choice: "deny" })
  })
})

describe("createUnboundGate concurrency", () => {
  test("two concurrent decides are independent", async () => {
    const gate = createUnboundGate({ emit: () => {} })
    const a = gate.decide(ask({ askId: "a" }))
    const b = gate.decide(ask({ askId: "b" }))
    expect(gate.pending().sort()).toEqual(["a", "b"])
    expect(gate.answer("b", "deny")).toBe(true)
    expect(await b).toEqual({ choice: "deny" })
    expect(gate.pending()).toEqual(["a"])
    expect(gate.answer("a", "bind", "op-1")).toBe(true)
    expect(await a).toEqual({ choice: "bind", operationId: "op-1" })
    expect(gate.pending()).toEqual([])
  })

  test("pending lists askIds generated by the gate", () => {
    const gate = createUnboundGate({ emit: () => {} })
    gate.decide(ask({ askId: "x" }))
    expect(gate.pending()).toEqual(["x"])
  })
})

describe("createUnboundGate timeout", () => {
  test("times out fail-open to allow-once and logs", async () => {
    const logs: unknown[][] = []
    const gate = createUnboundGate({
      timeoutMs: 10,
      emit: () => {},
      log: (...args) => logs.push(args),
    })
    const pending = gate.decide(ask({ askId: "slow" }))
    expect(gate.pending()).toEqual(["slow"])
    expect(await pending).toEqual({ choice: "allow-once" })
    expect(gate.pending()).toEqual([])
    expect(gate.answer("slow", "deny")).toBe(false)
    expect(logs.length).toBe(1)
    expect(logs[0]![0]).toBe("[hopper] guard.ask timed out, proceeding:")
    expect(logs[0]![1]).toBe("slow")
  })

  test("answer just before timeout wins the race", async () => {
    const gate = createUnboundGate({ timeoutMs: 50, emit: () => {} })
    const pending = gate.decide(ask({ askId: "race" }))
    expect(gate.answer("race", "bind", "op-race")).toBe(true)
    expect(await pending).toEqual({ choice: "bind", operationId: "op-race" })
    // late timeout must not log or re-resolve
    await Bun.sleep(70)
    expect(gate.pending()).toEqual([])
  })

  test("unconsumed timeout does not reject", async () => {
    const gate = createUnboundGate({ timeoutMs: 10, emit: () => {} })
    gate.decide(ask({ askId: "ignored" }))
    await Bun.sleep(30)
    expect(gate.pending()).toEqual([])
  })
})
