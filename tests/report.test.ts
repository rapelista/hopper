import { describe, expect, test, beforeAll, afterAll } from "bun:test"
import { mkdirSync, rmSync, existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { tmpdir } from "node:os"
import { HopperStore } from "../src/lib/store"
import { renderReportMarkdown, writeReport } from "../src/lib/report"
import { captureEvidence } from "../src/lib/evidence"
import { buildTools } from "../src/lib/tools"

let configDir: string
let store: HopperStore
let opId: string

beforeAll(() => {
  configDir = join(tmpdir(), "hopper-t15-" + Date.now())
  rmSync(configDir, { recursive: true, force: true })
  mkdirSync(configDir, { recursive: true })
  store = HopperStore.open(configDir)
  const op = store.createOperation("juice-shop", "http://localhost:3000")
  opId = op.id
  const info = store.addFinding(opId, { title: "Info header missing", severity: "info", target: "localhost:3000" })
  const crit = store.addFinding(opId, { title: "RCE in profile pic", severity: "critical", target: "localhost:3000" })
  store.updateFindingStatus(crit.id, "observed")
  store.updateFindingStatus(crit.id, "verified")
  store.updateFindingStatus(crit.id, "reportable")
  const cap = captureEvidence("response", "HTTP/1.1 200 OK\nwhoami=root")
  store.saveEvidence(opId, cap, "HTTP/1.1 200 OK\nwhoami=root")
  store.attachEvidence(crit.id, cap.id)
  void info
})

afterAll(() => {
  store.close()
  rmSync(configDir, { recursive: true, force: true })
})

describe("renderReportMarkdown", () => {
  test("renders operation header and both findings, severity ordered", () => {
    const md = renderReportMarkdown(store, opId)
    expect(md).toContain("juice-shop")
    expect(md).toContain("RCE in profile pic")
    expect(md).toContain("Info header missing")
    expect(md.indexOf("RCE in profile pic")).toBeLessThan(md.indexOf("Info header missing"))
    expect(md).toContain("Generated by Hopper")
  })

  test("reportable finding carries evidence sha256 prefix", () => {
    const md = renderReportMarkdown(store, opId)
    expect(md).toMatch(/sha256[: ]+[0-9a-f]{16}/)
  })

  test("empty operation renders a no-findings section", () => {
    const emptyOp = store.createOperation("empty", "http://nowhere.test")
    const md = renderReportMarkdown(store, emptyOp.id)
    expect(md).toContain("No findings recorded")
  })
})

describe("writeReport", () => {
  test("writes a report file and returns its path", () => {
    const path = writeReport(configDir, opId)
    expect(existsSync(path)).toBe(true)
    expect(path).toMatch(/reports\/.*\.md$/)
    expect(readFileSync(path, "utf8")).toContain("juice-shop")
  })
})

describe("report tool shape", () => {
  test("tool has description and executable content", () => {
    const t = buildTools("/tmp").find((x) => x.name === "report")!
    expect(t.description.length).toBeGreaterThan(10)
    expect(typeof t.execute).toBe("function")
  })
})
